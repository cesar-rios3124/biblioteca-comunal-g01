-- Script 01: creación de las cinco tablas del negocio en Oracle FreeSQL.
-- Ejecutar como script en el esquema personal de cada integrante.
-- ATENCIÓN: este script elimina las tablas del proyecto si ya existen y sus datos.

-- 1. Eliminar en orden inverso a las dependencias.
DROP TABLE IF EXISTS detalle_prestamo CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS prestamos        CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS libros            CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS generos           CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS socios            CASCADE CONSTRAINTS PURGE;

-- 2. Tabla SOCIOS.
CREATE TABLE socios (
    id_socio NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    rut      VARCHAR2(12)  NOT NULL,
    nombre   VARCHAR2(100) NOT NULL,
    email    VARCHAR2(100),
    telefono VARCHAR2(20),
    activo   NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_socios PRIMARY KEY (id_socio),
    CONSTRAINT uq_socios_rut UNIQUE (rut),
    CONSTRAINT ck_socios_activo CHECK (activo IN (0, 1))
);

-- 3. Tabla GENEROS.
CREATE TABLE generos (
    id_genero NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    nombre    VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_generos PRIMARY KEY (id_genero),
    CONSTRAINT uq_generos_nombre UNIQUE (nombre)
);

-- 4. Tabla LIBROS. Cada libro pertenece a un género.
CREATE TABLE libros (
    id_libro               NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    isbn                   VARCHAR2(20)  NOT NULL,
    titulo                 VARCHAR2(150) NOT NULL,
    autor                  VARCHAR2(100) NOT NULL,
    anio                   NUMBER(4) NOT NULL,
    id_genero              NUMBER(11) NOT NULL,
    ejemplares_disponibles NUMBER(11) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_libros PRIMARY KEY (id_libro),
    CONSTRAINT uq_libros_isbn UNIQUE (isbn),
    CONSTRAINT fk_libros_genero FOREIGN KEY (id_genero)
        REFERENCES generos (id_genero),
    CONSTRAINT ck_libros_ejemplares CHECK (ejemplares_disponibles >= 0)
);

-- 5. Tabla PRESTAMOS. Cada préstamo pertenece a un socio.
CREATE TABLE prestamos (
    id_prestamo               NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    id_socio                  NUMBER(11) NOT NULL,
    fecha_prestamo            TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_devolucion_esperada TIMESTAMP NOT NULL,
    estado                    VARCHAR2(10) DEFAULT 'activo' NOT NULL,
    CONSTRAINT pk_prestamos PRIMARY KEY (id_prestamo),
    CONSTRAINT fk_prestamos_socio FOREIGN KEY (id_socio)
        REFERENCES socios (id_socio),
    CONSTRAINT ck_prestamos_estado CHECK (estado IN ('activo', 'atrasado', 'devuelto'))
);

-- 6. Tabla DETALLE_PRESTAMO.
-- La clave primaria compuesta impide repetir el mismo libro dentro del mismo préstamo.
CREATE TABLE detalle_prestamo (
    id_prestamo NUMBER(11) NOT NULL,
    id_libro    NUMBER(11) NOT NULL,
    cantidad    NUMBER(11) NOT NULL,
    CONSTRAINT pk_detalle_prestamo PRIMARY KEY (id_prestamo, id_libro),
    CONSTRAINT fk_detalle_prestamo FOREIGN KEY (id_prestamo)
        REFERENCES prestamos (id_prestamo),
    CONSTRAINT fk_detalle_libro FOREIGN KEY (id_libro)
        REFERENCES libros (id_libro),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0)
);

-- 7. Índices para las claves foráneas.
-- La PK compuesta de DETALLE_PRESTAMO comienza por id_prestamo,
-- por lo que su índice ya cubre esa FK y no se crea uno duplicado.
CREATE INDEX ix_libros_genero ON libros (id_genero);
CREATE INDEX ix_prestamos_socio ON prestamos (id_socio);
CREATE INDEX ix_detalle_prestamo_libro ON detalle_prestamo (id_libro);

-- 8. Verificación de las tablas creadas.
SELECT table_name
FROM user_tables
WHERE table_name IN ('SOCIOS', 'GENEROS', 'LIBROS', 'PRESTAMOS', 'DETALLE_PRESTAMO')
ORDER BY table_name;
